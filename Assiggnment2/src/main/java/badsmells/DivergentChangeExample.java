package badsmells;

/*
 * Smell: Divergent Change
 *
 * Problem: One class handled report formatting, SQL generation, and CSV export,
 * so any unrelated change risked breaking the other two concerns.
 *
 * Refactoring: Split the class into three focused classes — ReportFormatter,
 * SqlBuilder, and CsvExporter — each owning only its own fields and methods.
 *
 * Result: Each class now changes for exactly one reason, following the
 * Single Responsibility Principle and Separation of Concerns.
 */
public class DivergentChangeExample {

	static class ReportFormatter {
		private String title = "Exam Results";
		private String footer = "Generated by registrar office";

		public String format(String name, int score) {
			return title + "\n" + name + ": " + score + "\n" + footer;
		}
	}

	static class SqlBuilder {
		private String tableName = "exam_results";
		private String databaseUrl = "jdbc:mysql://localhost:3306/school";

		public String buildInsert(String name, int score) {
			return "/* " + databaseUrl + " */ INSERT INTO " + tableName
				+ "(name, score) VALUES ('" + name + "', " + score + ")";
		}
	}

	static class CsvExporter {
		private String separator = ",";
		private boolean includeHeader = true;

		public String export(String name, int score) {
			String csv = name + separator + score;
			if (includeHeader) {
				return "name" + separator + "score\n" + csv;
			}
			return csv;
		}
	}

	public void clientCode() {
		ReportFormatter report = new ReportFormatter();
		SqlBuilder sql = new SqlBuilder();
		CsvExporter csv = new CsvExporter();

		System.out.println(report.format("Nino", 95));
		System.out.println(sql.buildInsert("Nino", 95));
		System.out.println(csv.export("Nino", 95));
	}
}